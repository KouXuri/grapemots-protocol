#!/usr/bin/env python3
"""Online Resource 1 of the 15-page Precision Agriculture submission (2026-11-21).

Every paragraph and table is copied verbatim from the verified long version (manuscript/main.tex); only
cross-references are renumbered (Tables S1-S4, Figs. S1-S2, figures of the main text cited by number) and
sections are regrouped. The four control runs described in the long version's "Experimental design"
(phase, scaled buffer, extra Kalman steps, ByteTrack on real detections) are not reproduced, because no
statement of the article rests on them; their outputs are part of the archived release.
Figures: figures/pa_submission/FigS1.pdf, FigS2.pdf (tools/make_figures_pa119_1121.py).
Output: manuscript_pa/online_resource_1.tex; compile with tectonic.
    .venv/bin/python cadence_journal_1119/tools/build_or1_pa15_1121.py
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
src = (HERE / "manuscript/main.tex").read_text()


def between(a: str, b: str) -> str:
    i = src.index(a)
    j = src.index(b, i)
    return src[i + len(a):j].strip("\n")


def env(label: str) -> str:
    k = src.index("\\label{" + label + "}")
    i = src.rindex("\\begin{table}", 0, k)
    j = src.index("\\end{table}", k) + len("\\end{table}")
    return src[i:j].replace("[t]", "[htbp]")


def para(start: str) -> str:
    i = src.index(start)
    j = src.index("\n\n", i)
    return src[i:j]


data = between("\\subsection{Data}", "\\begin{table}[t]\n\\caption{Test sequences")
detectors = between("\\subsection{Detectors}", "\\begin{table}[t]\n\\caption{Whole-frame detectors")
tracking = between("\\subsection{Tracking and the processing protocol}", "\\subsection{Count error and its decomposition}")
assoc = between("\\subsection{Association alone}", "\\subsection{Detector errors and their attribution}")
errors = between("\\subsection{Detector errors and their attribution}", "\\subsection{Vine-level validity and calibration}")
identity = between("\\subsection{Identity metrics, cost and statistics}", "\\emph{Use of language models.}")
sparser = para("Sparser processing did not reduce the oracle surplus.")
interval = para("The misses also set how the count moved with the interval.")
crossing = para("Where the count crossed zero depended on the checkpoint")
hota = para("Choosing a configuration by its count picked compensating errors")
vines = para("Across vines the two sides of the account moved in opposite directions.")

body = "\n\n".join([
    "\\section*{S1 Data}", data, env("tab:data"),
    "\\section*{S2 Detectors}", detectors, env("tab:training"),
    "\\section*{S3 Tracking and the processing protocol}", tracking,
    "\\section*{S4 Association alone}", assoc, env("tab:oracle"), sparser,
    "\\section*{S5 Detector errors, their attribution and the confidence gate}", errors, interval,
    "\\section*{S6 Where the count changes sign}", crossing,
    "\\section*{S7 Identity metrics, processing cost and statistics}", identity, hota,
    "\\section*{S8 Calibration}", env("tab:calibration"), vines,
])
REPL = [("(Table 1)", "(Table~S1)"), ("Each\ntest video has its own fold (Table 1).", "Each\ntest video has its own fold (Table~S1)."),
        ("(Table 2)", "(Table~S2)"), ("Table~\\ref{tab:oracle}, Fig.~\\ref{fig:oracle}", "Table~S3; Fig.~1 of the main text"),
        ("Fig.~\\ref{fig:map}", "Fig.~S1"), ("Fig.~\\ref{fig:hota}", "Fig.~S2"),
        ("Table~\\ref{tab:shapley}", "Table~1 of the main text"), ("Table~\\ref{tab:calibration}", "Table~S4"),
        ("Fig.~\\ref{fig:terms}", "Fig.~3 of the main text"), ("Fig.~\\ref{fig:vines}", "Fig.~4 of the main text"),
        ("Fig.~\\ref{fig:missalone}", "Fig.~2 of the main text")]
for a, b in REPL:
    body = body.replace(a, b)
assert "\\ref{fig:" not in body, re.findall(r"\\ref\{fig:[^}]*\}", body)
assert "Table 1" not in body and "Table 2" not in body and "Table 6" not in body

head = r"""% Online Resource 1 of the Precision Agriculture submission. Generated by tools/build_or1_pa15_1121.py
% from manuscript/main.tex (2026-11-21); edit the long version and regenerate, not this file.
\documentclass[11pt]{article}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath}
\usepackage[margin=25mm]{geometry}
\usepackage{graphicx}
\usepackage{amsmath}
\usepackage{booktabs}
\usepackage{xcolor}
\usepackage[round,authoryear]{natbib}
\usepackage[hidelinks]{hyperref}
\newcommand{\pend}[1]{\textcolor{red}{[#1]}}
\graphicspath{{../figures/pa_submission/}}
\renewcommand{\thetable}{S\arabic{table}}
\renewcommand{\thefigure}{S\arabic{figure}}
\renewcommand{\theequation}{S\arabic{equation}}
\begin{document}
\begin{center}
{\large\bfseries Online Resource 1}\\[6pt]
{\bfseries When finding more bunches makes the count worse: identity errors in tracking-based grape-bunch
counting from multi-view UAV video}\\[4pt]
\emph{Precision Agriculture}\\[4pt]
Xuri Kou, Wen Qiu, Musen Cheng, Taihui Liu, Hiroshi Masui\\[2pt]
\small Corresponding author: Xuri Kou, Division of Information and Communication Engineering, Kitami
Institute of Technology, Kitami, Japan; kouxuri@gmail.com
\end{center}

\noindent This file gives the methods omitted from the article in full, further results cited there,
Tables S1--S4 and Figs.~S1--S2. Figures~1--4 and Tables~1--3 are those of the article.

"""
figs = r"""
\begin{figure}[htbp]
\centering
\includegraphics[width=119mm]{FigS1.pdf}
\caption{Interval bracket in which the count error changes sign, per test video and inference scale, for
the six detector sets}
\label{fig:S1}
\end{figure}

\begin{figure}[htbp]
\centering
\includegraphics[width=119mm]{FigS2.pdf}
\caption{\textbf{a} Median HOTA over the 21 video--seed cases of the whole-frame detectors by processing
interval, at the processed frames (solid) and on all annotated frames after linear interpolation (dotted).
\textbf{b} For each case, the arm with the highest HOTA (circle) and the arm with the smallest count error
(square), joined by an arrow}
\label{fig:S2}
\end{figure}
"""
tail = figs + "\n\\bibliographystyle{plainnat}\n\\bibliography{refs}\n\n\\end{document}\n"
(HERE / "manuscript_pa/online_resource_1.tex").write_text(head + body + "\n" + tail)
print("written online_resource_1.tex")
